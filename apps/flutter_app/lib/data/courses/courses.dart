/// День мини-курса: теория + упражнение + вопрос для рефлексии.
class CourseDay {
  final String title;
  final String theory; // markdown
  final String exercise; // markdown
  final String reflectionPrompt;

  const CourseDay({
    required this.title,
    required this.theory,
    required this.exercise,
    required this.reflectionPrompt,
  });
}

